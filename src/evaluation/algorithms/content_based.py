"""
Content-based recommendation using Sentence Transformers.

This algorithm embeds item content using a Sentence Transformer model.
User profiles are generated by averaging embeddings of their interactions.
Supports two backends for nearest neighbor search:
- sklearn: More reliable, recommended for most cases
- annoy: Faster for very large datasets (requires correct sequential indexing)
"""

from typing import Dict, Optional, Any
import numpy as np
from scipy.sparse import lil_matrix, csr_matrix
import pandas as pd

from ...utils.logging import get_logger


logger = get_logger("evaluation.algorithms.content_based")


# Check for required dependencies
try:
    from recpack.algorithms.base import Algorithm
    HAS_RECPACK = True
except ImportError:
    HAS_RECPACK = False
    Algorithm = object  # Dummy base class

try:
    from sentence_transformers import SentenceTransformer
    HAS_SENTENCE_TRANSFORMERS = True
except ImportError:
    HAS_SENTENCE_TRANSFORMERS = False

try:
    from sklearn.neighbors import NearestNeighbors
    HAS_SKLEARN = True
except ImportError:
    HAS_SKLEARN = False

try:
    from annoy import AnnoyIndex
    HAS_ANNOY = True
except ImportError:
    HAS_ANNOY = False


def check_dependencies(backend: str = 'sklearn'):
    """Check if all required dependencies are available."""
    missing = []
    if not HAS_RECPACK:
        missing.append('recpack')
    if not HAS_SENTENCE_TRANSFORMERS:
        missing.append('sentence-transformers')
    if backend == 'sklearn' and not HAS_SKLEARN:
        missing.append('scikit-learn')
    if backend == 'annoy' and not HAS_ANNOY:
        missing.append('annoy')
    
    if missing:
        raise ImportError(
            f"Missing dependencies: {', '.join(missing)}. "
            f"Install with: pip install {' '.join(missing)}"
        )


class SentenceTransformerContentBased(Algorithm):
    """Content-based recommendation using Sentence Transformers.
    
    Embeds item content using a Sentence Transformer model. User profiles are
    generated by averaging the embeddings of items they interacted with.
    
    Supports two backends for nearest neighbor search:
    - 'sklearn': Uses sklearn's NearestNeighbors (default, reliable)
    - 'annoy': Uses Spotify's Annoy (faster for large datasets)
    
    Args:
        content: Dictionary mapping item IDs to content strings, or
                 DataFrame with article_id and content columns
        item_mapping: Optional mapping from original item IDs to internal IDs
        model_name: Sentence Transformer model name
        metric: Distance metric ('cosine', 'euclidean')
        embedding_dim: Embedding dimension (None = auto-detect)
        num_neighbors: Number of neighbors to retrieve
        verbose: Whether to print progress
        backend: 'sklearn' (default) or 'annoy'
        annoy_n_trees: Number of trees for Annoy index (more = better accuracy)
        annoy_search_k: Search parameter for Annoy (-1 for auto)
    """
    
    def __init__(
        self,
        content: Dict[int, str] | pd.DataFrame,
        item_mapping: Optional[Dict[str, int]] = None,
        model_name: str = 'intfloat/multilingual-e5-large',
        metric: str = 'cosine',
        embedding_dim: Optional[int] = None,
        num_neighbors: int = 100,
        verbose: bool = False,
        content_df: Optional[pd.DataFrame] = None,  # Alias for compatibility
        backend: str = 'sklearn',  # 'sklearn' or 'annoy'
        annoy_n_trees: int = 50,
        annoy_search_k: int = -1,  # -1 means auto
    ):
        check_dependencies(backend)
        super().__init__()
        
        # Handle DataFrame or dict input
        if content_df is not None:
            content = content_df
        
        if isinstance(content, pd.DataFrame):
            self.content = self._df_to_content_dict(content, item_mapping)
        else:
            self.content = content
        
        self.item_mapping = item_mapping
        self.model_name = model_name
        self.metric = metric
        self.embedding_dim = embedding_dim
        self.num_neighbors = num_neighbors
        self.verbose = verbose
        self.backend = backend
        self.annoy_n_trees = annoy_n_trees
        self.annoy_search_k = annoy_search_k
        
        # Also store under legacy names for compatibility
        self.language = model_name
        
        # Initialize model
        self.model = SentenceTransformer(self.model_name)
        
        # Get embedding dimension
        if self.embedding_dim is None:
            dummy = self.model.encode("test")
            self._embedding_dim = dummy.shape[0]
        else:
            self._embedding_dim = self.embedding_dim
        
        # Backend-specific indices (will be initialized in _fit)
        self._nn_index: Optional[Any] = None  # sklearn NearestNeighbors
        self._annoy_index: Optional[Any] = None  # Annoy index
        self._item_embeddings_matrix: Optional[np.ndarray] = None
        self._item_id_to_idx: Dict[int, int] = {}  # Maps internal item ID to matrix row
        self._idx_to_item_id: Dict[int, int] = {}  # Maps matrix row to internal item ID
        
        # Internal state
        self._item_embeddings: Dict[int, np.ndarray] = {}
        
        logger.info(f"Initialized ContentBased with {len(self.content)} items, "
                   f"embedding dim={self._embedding_dim}, backend={backend}")
    
    @staticmethod
    def _df_to_content_dict(
        df: pd.DataFrame,
        item_mapping: Optional[Dict[str, int]] = None,
    ) -> Dict[int, str]:
        """Convert DataFrame to content dictionary.
        
        Args:
            df: DataFrame with article_id and content columns
            item_mapping: Optional mapping from article_id to internal ID
            
        Returns:
            Dictionary mapping internal IDs to content strings
        """
        content_dict = {}
        
        for _, row in df.iterrows():
            article_id = str(row.get('article_id', row.get('item_id', '')))
            content_text = row.get('content', row.get('text', ''))
            
            if item_mapping:
                internal_id = item_mapping.get(article_id)
                if internal_id is not None:
                    content_dict[internal_id] = content_text
            else:
                try:
                    internal_id = int(article_id)
                    content_dict[internal_id] = content_text
                except ValueError:
                    pass
        
        return content_dict
    
    def _log(self, msg: str):
        """Log message if verbose mode enabled."""
        if self.verbose:
            logger.info(msg)
    
    def _fit(self, X: csr_matrix):
        """Fit the model on interaction data.
        
        Args:
            X: User-item interaction matrix
        """
        num_users, num_items = X.shape
        
        self._log(f"Fitting model: {num_users} users, {num_items} items")
        
        # Collect items with content
        item_ids = []
        content_texts = []
        
        for item_id in range(num_items):
            text = self.content.get(item_id)
            if text:
                item_ids.append(item_id)
                content_texts.append(text)
        
        self._log(f"Found content for {len(item_ids)}/{num_items} items")
        
        # Encode item content
        if content_texts:
            embeddings = self.model.encode(
                content_texts,
                show_progress_bar=self.verbose,
            )
            
            self._item_embeddings = dict(zip(item_ids, embeddings))
            
            # Build embeddings matrix and mappings
            # CRITICAL: Use sequential indices (0, 1, 2, ...) for both backends
            self._item_id_to_idx = {item_id: idx for idx, item_id in enumerate(item_ids)}
            self._idx_to_item_id = {idx: item_id for idx, item_id in enumerate(item_ids)}
            self._item_embeddings_matrix = np.array(embeddings)
            
            # Build backend-specific index
            if self.backend == 'annoy':
                self._build_annoy_index(item_ids, embeddings)
            else:
                self._build_sklearn_index(item_ids, embeddings)
            
        else:
            self._item_embeddings = {}
            self._item_embeddings_matrix = None
            self._nn_index = None
            self._annoy_index = None
            logger.warning("No item content found to encode")
        
        # Set fitted attributes
        self.n_features_in_ = num_items
        self.n_users_ = num_users
        self.n_items_ = num_items
        
        self._log(f"Built {self.backend} index with {len(item_ids)} items")
    
    def _build_sklearn_index(self, item_ids, embeddings):
        """Build sklearn NearestNeighbors index."""
        n_neighbors = min(self.num_neighbors, len(item_ids))
        self._nn_index = NearestNeighbors(n_neighbors=n_neighbors, metric=self.metric)
        self._nn_index.fit(self._item_embeddings_matrix)
    
    def _build_annoy_index(self, item_ids, embeddings):
        """Build Annoy index with proper sequential indexing.
        
        IMPORTANT: Annoy indices must be sequential (0, 1, 2, ...).
        Using sparse IDs (like article_id=3198681) causes Annoy to create
        a huge sparse internal array, leading to poor search results.
        
        NOTE: Annoy has a known bug on Apple Silicon (M1/M2/M3 Macs) where
        it only returns 1 neighbor regardless of how many are requested.
        Use backend='sklearn' on Apple Silicon systems.
        """
        # Convert metric for Annoy
        annoy_metric = 'angular' if self.metric == 'cosine' else self.metric
        
        self._annoy_index = AnnoyIndex(self._embedding_dim, annoy_metric)
        
        # CRITICAL: Use sequential indices (0, 1, 2, ...), NOT item_ids!
        for idx, embedding in enumerate(embeddings):
            self._annoy_index.add_item(idx, embedding)
        
        self._annoy_index.build(self.annoy_n_trees)
        
        # Verify the index
        n_items = self._annoy_index.get_n_items()
        self._log(f"Annoy index built: {n_items} items, {self.annoy_n_trees} trees, metric={annoy_metric}")
        if n_items != len(item_ids):
            logger.warning(f"Annoy index size mismatch! Got {n_items}, expected {len(item_ids)}")
    
    def _predict(self, X: csr_matrix) -> csr_matrix:
        """Generate predictions for users.
        
        Args:
            X: User-item interaction matrix
            
        Returns:
            Prediction matrix
        """
        num_users, num_items = X.shape
        result = lil_matrix((num_users, num_items), dtype=np.float32)
        
        # Check if we have an index
        has_index = (self.backend == 'sklearn' and self._nn_index is not None) or \
                    (self.backend == 'annoy' and self._annoy_index is not None)
        
        if not has_index or self._item_embeddings_matrix is None:
            logger.warning("No item embeddings available for prediction")
            return result.tocsr()
        
        users_with_recs = 0
        
        for user_id in range(num_users):
            # Get user's interaction history
            user_items = X[user_id].nonzero()[1]
            
            if len(user_items) == 0:
                continue
            
            # Compute user embedding as mean of item embeddings
            user_embeddings = []
            for item_id in user_items:
                emb = self._item_embeddings.get(item_id)
                if emb is not None:
                    user_embeddings.append(emb)
            
            if not user_embeddings:
                continue
            
            user_embedding = np.mean(user_embeddings, axis=0)
            
            # Query the appropriate backend
            if self.backend == 'annoy':
                nn_indices, distances = self._query_annoy(user_embedding)
            else:
                nn_indices, distances = self._query_sklearn(user_embedding)
            
            # Convert matrix indices back to item IDs and filter interacted items
            user_items_set = set(user_items)
            recommendations = []
            
            for matrix_idx, dist in zip(nn_indices, distances):
                item_id = self._idx_to_item_id[matrix_idx]
                if item_id not in user_items_set:
                    score = self._distance_to_similarity(dist)
                    recommendations.append((item_id, score))
            
            # Take top-k
            recommendations.sort(key=lambda x: x[1], reverse=True)
            
            for item_id, score in recommendations[:self.num_neighbors]:
                if 0 <= item_id < num_items:
                    result[user_id, item_id] = score
            
            if recommendations:
                users_with_recs += 1
        
        self._log(f"Generated recommendations for {users_with_recs}/{num_users} users")
        
        return result.tocsr()
    
    def _query_sklearn(self, user_embedding: np.ndarray):
        """Query sklearn NearestNeighbors index."""
        user_embedding = user_embedding.reshape(1, -1)
        distances, nn_indices = self._nn_index.kneighbors(user_embedding)
        return nn_indices[0], distances[0]
    
    def _query_annoy(self, user_embedding: np.ndarray):
        """Query Annoy index with proper search_k.
        
        NOTE: Annoy has a known bug on Apple Silicon (M1/M2/M3 Macs) where
        it only returns 1 neighbor regardless of how many are requested.
        Use backend='sklearn' on Apple Silicon systems.
        """
        # Calculate search_k if auto
        search_k = self.annoy_search_k
        if search_k < 0:
            search_k = self.annoy_n_trees * self.num_neighbors * 10  # Be generous
        
        # Check index state
        n_items_in_index = self._annoy_index.get_n_items()
        if n_items_in_index == 0:
            logger.warning("Annoy index is empty!")
            return [], []
        
        # Query returns sequential indices, not item IDs!
        nn_indices, distances = self._annoy_index.get_nns_by_vector(
            user_embedding,
            min(self.num_neighbors, n_items_in_index),
            search_k=search_k,
            include_distances=True,
        )
        
        return nn_indices, distances
    
    def _distance_to_similarity(self, distance: float) -> float:
        """Convert distance to similarity score.
        
        Args:
            distance: Distance value from sklearn or Annoy
            
        Returns:
            Similarity score
        """
        if self.backend == 'annoy':
            # Annoy angular distance: sqrt(2 * (1 - cos(u, v)))
            # So: cos(u, v) = 1 - (distance^2 / 2)
            return max(0, 1.0 - (distance ** 2) / 2.0)
        elif self.metric == 'cosine':
            # sklearn cosine distance: 1 - cos_sim
            # So similarity = 1 - dist
            return 1.0 - distance
        elif self.metric == 'euclidean':
            return np.exp(-distance)
        else:
            return 1.0 / (1.0 + distance)
