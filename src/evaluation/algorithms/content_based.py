"""
Content-based recommendation using Sentence Transformers or pre-calculated embeddings.

This algorithm embeds item content using a Sentence Transformer model OR uses
pre-calculated embeddings from a parquet file (much faster for large datasets).
User profiles are generated by averaging embeddings of their interactions.

Supports two backends for nearest neighbor search:
- annoy: Default, faster for large datasets using approximate nearest neighbors
- sklearn: More reliable exact search, use if annoy has issues

WARNING: Annoy has a known bug on Apple Silicon (M1/M2/M3/M4 Macs) where it may
only return 1 neighbor regardless of how many are requested. Use backend='sklearn'
on Apple Silicon systems if you experience this issue.
"""

from typing import Dict, Optional, Any
import numpy as np
from scipy.sparse import lil_matrix, csr_matrix
import pandas as pd

from ...utils.logging import get_logger


logger = get_logger("evaluation.algorithms.content_based")


# Check for required dependencies
try:
    from recpack.algorithms.base import Algorithm
    HAS_RECPACK = True
except ImportError:
    HAS_RECPACK = False
    Algorithm = object  # Dummy base class

try:
    from sentence_transformers import SentenceTransformer
    HAS_SENTENCE_TRANSFORMERS = True
except ImportError:
    HAS_SENTENCE_TRANSFORMERS = False

try:
    from sklearn.neighbors import NearestNeighbors
    HAS_SKLEARN = True
except ImportError:
    HAS_SKLEARN = False

try:
    from annoy import AnnoyIndex
    HAS_ANNOY = True
except ImportError:
    HAS_ANNOY = False


def check_dependencies(backend: str = 'sklearn', use_precalculated: bool = False):
    """Check if all required dependencies are available."""
    missing = []
    if not HAS_RECPACK:
        missing.append('recpack')
    # Only require sentence-transformers if NOT using pre-calculated embeddings
    if not use_precalculated and not HAS_SENTENCE_TRANSFORMERS:
        missing.append('sentence-transformers')
    if backend == 'sklearn' and not HAS_SKLEARN:
        missing.append('scikit-learn')
    if backend == 'annoy' and not HAS_ANNOY:
        missing.append('annoy')
    
    if missing:
        raise ImportError(
            f"Missing dependencies: {', '.join(missing)}. "
            f"Install with: pip install {' '.join(missing)}"
        )


class SentenceTransformerContentBased(Algorithm):
    """Content-based recommendation using Sentence Transformers or pre-calculated embeddings.
    
    Embeds item content using a Sentence Transformer model OR uses pre-calculated
    embeddings from a parquet file (much faster for large datasets like EB-NeRD).
    User profiles are generated by averaging the embeddings of items they interacted with.
    
    Supports two backends for nearest neighbor search:
    - 'annoy': Uses Spotify's Annoy (default, faster for large datasets)
    - 'sklearn': Uses sklearn's NearestNeighbors (reliable exact search)
    
    WARNING: Annoy has a known bug on Apple Silicon (M1/M2/M3/M4 Macs) where it may
    only return 1 neighbor regardless of how many are requested. Use backend='sklearn'
    on Apple Silicon systems if you experience this issue.
    
    Args:
        content: Dictionary mapping item IDs to content strings, or
                 DataFrame with article_id and content columns
        item_mapping: Optional mapping from original item IDs to internal IDs
        model_name: Sentence Transformer model name (ignored if embeddings provided)
        metric: Distance metric ('cosine', 'euclidean')
        embedding_dim: Embedding dimension (None = auto-detect)
        num_neighbors: Number of neighbors to retrieve
        verbose: Whether to print progress
        backend: 'annoy' (default) or 'sklearn'
        annoy_n_trees: Number of trees for Annoy index (more = better accuracy)
        annoy_search_k: Search parameter for Annoy (-1 for auto)
        embeddings: Optional DataFrame with pre-calculated embeddings.
                    Expected schema: article_id (int), embedding_column (list[float])
                    If provided, skips loading SentenceTransformer model entirely.
        embedding_column: Name of the column containing embeddings in embeddings DataFrame.
                         Default: 'embedding' (from generate_embeddings.py)
    """
    
    def __init__(
        self,
        content: Dict[int, str] | pd.DataFrame,
        item_mapping: Optional[Dict[str, int]] = None,
        model_name: str = 'intfloat/multilingual-e5-large',
        metric: str = 'cosine',
        embedding_dim: Optional[int] = None,
        num_neighbors: int = 100,
        verbose: bool = False,
        content_df: Optional[pd.DataFrame] = None,  # Alias for compatibility
        backend: str = 'annoy',  # 'annoy' (default) or 'sklearn'
        annoy_n_trees: int = 50,
        annoy_search_k: int = -1,  # -1 means auto
        embeddings: Optional[pd.DataFrame] = None,  # Pre-calculated embeddings
        embedding_column: str = 'embedding',  # Column from generate_embeddings.py
    ):
        # Determine if we're using pre-calculated embeddings
        self._use_precalculated = embeddings is not None
        
        check_dependencies(backend, use_precalculated=self._use_precalculated)
        super().__init__()
        
        # Store pre-calculated embeddings if provided
        self._precalculated_embeddings: Optional[pd.DataFrame] = embeddings
        self._embedding_column = embedding_column
        
        # Handle DataFrame or dict input for content
        if content_df is not None:
            content = content_df
        
        if isinstance(content, pd.DataFrame):
            self.content = self._df_to_content_dict(content, item_mapping)
        else:
            self.content = content
        
        self.item_mapping = item_mapping
        self.model_name = model_name
        self.metric = metric
        self.embedding_dim = embedding_dim
        self.num_neighbors = num_neighbors
        self.verbose = verbose
        self.backend = backend
        self.annoy_n_trees = annoy_n_trees
        self.annoy_search_k = annoy_search_k
        
        # Warn about Apple Silicon compatibility
        if backend == 'annoy':
            import platform
            if platform.processor() == 'arm' or 'arm' in platform.machine().lower():
                logger.warning("=" * 60)
                logger.warning("WARNING: Annoy backend on Apple Silicon (M1/M2/M3/M4)")
                logger.warning("=" * 60)
                logger.warning("Annoy has a known bug on Apple Silicon where it may only")
                logger.warning("return 1 neighbor regardless of how many are requested.")
                logger.warning("If you see poor CB-ST results, try: backend='sklearn'")
                logger.warning("=" * 60)
        
        # Also store under legacy names for compatibility
        self.language = model_name
        
        # Initialize model only if NOT using pre-calculated embeddings
        if self._use_precalculated:
            self.model = None
            # Detect embedding dimension from the pre-calculated embeddings
            if self.embedding_dim is None:
                # Get first non-null embedding to detect dimension
                sample_emb = self._precalculated_embeddings[embedding_column].dropna().iloc[0]
                self._embedding_dim = len(sample_emb)
            else:
                self._embedding_dim = self.embedding_dim
            logger.info(f"Using pre-calculated embeddings from column '{embedding_column}', "
                       f"embedding dim={self._embedding_dim}")
        else:
            self.model = SentenceTransformer(self.model_name)
            # Get embedding dimension
            if self.embedding_dim is None:
                dummy = self.model.encode("test")
                self._embedding_dim = dummy.shape[0]
            else:
                self._embedding_dim = self.embedding_dim
        
        # Backend-specific indices (will be initialized in _fit)
        self._nn_index: Optional[Any] = None  # sklearn NearestNeighbors
        self._annoy_index: Optional[Any] = None  # Annoy index
        self._item_embeddings_matrix: Optional[np.ndarray] = None
        self._item_id_to_idx: Dict[int, int] = {}  # Maps internal item ID to matrix row
        self._idx_to_item_id: Dict[int, int] = {}  # Maps matrix row to internal item ID
        
        # Internal state
        self._item_embeddings: Dict[int, np.ndarray] = {}
        
        n_items = len(self._precalculated_embeddings) if self._use_precalculated else len(self.content)
        logger.info(f"Initialized ContentBased with {n_items} items, "
                   f"embedding dim={self._embedding_dim}, backend={backend}, "
                   f"precalculated={self._use_precalculated}")
    
    @staticmethod
    def _df_to_content_dict(
        df: pd.DataFrame,
        item_mapping: Optional[Dict[str, int]] = None,
    ) -> Dict[int, str]:
        """Convert DataFrame to content dictionary.
        
        Vectorized implementation for performance.
        
        Args:
            df: DataFrame with article_id and content columns
            item_mapping: Optional mapping from article_id to internal ID
            
        Returns:
            Dictionary mapping internal IDs to content strings
        """
        # Get article_id column (try both names)
        if 'article_id' in df.columns:
            article_ids = df['article_id'].astype(str)
        elif 'item_id' in df.columns:
            article_ids = df['item_id'].astype(str)
        else:
            return {}
        
        # Get content column (try both names)
        if 'content' in df.columns:
            content_texts = df['content']
        elif 'text' in df.columns:
            content_texts = df['text']
        else:
            return {}
        
        if item_mapping:
            # Vectorized mapping: map article_ids to internal IDs
            internal_ids = article_ids.map(item_mapping)
            
            # Filter to valid mappings (non-null)
            valid_mask = internal_ids.notna()
            valid_ids = internal_ids[valid_mask].astype(int)
            valid_content = content_texts[valid_mask]
            
            return dict(zip(valid_ids, valid_content))
        else:
            # No mapping: try to convert article_ids to int directly
            # Use pd.to_numeric with errors='coerce' to handle non-numeric IDs
            numeric_ids = pd.to_numeric(article_ids, errors='coerce')
            valid_mask = numeric_ids.notna()
            valid_ids = numeric_ids[valid_mask].astype(int)
            valid_content = content_texts[valid_mask]
            
            return dict(zip(valid_ids, valid_content))
    
    def _log(self, msg: str):
        """Log message if verbose mode enabled."""
        if self.verbose:
            logger.info(msg)
    
    def _fit(self, X: csr_matrix):
        """Fit the model on interaction data.
        
        Args:
            X: User-item interaction matrix
        """
        num_users, num_items = X.shape
        
        self._log(f"Fitting model: {num_users} users, {num_items} items")
        
        if self._use_precalculated:
            # Use pre-calculated embeddings
            item_ids, embeddings = self._load_precalculated_embeddings(num_items)
        else:
            # Encode with SentenceTransformer model
            item_ids, embeddings = self._encode_content(num_items)
        
        self._log(f"Found embeddings for {len(item_ids)}/{num_items} items")
        
        if len(item_ids) > 0 and embeddings is not None:
            self._item_embeddings = dict(zip(item_ids, embeddings))
            
            # Build embeddings matrix and mappings
            # CRITICAL: Use sequential indices (0, 1, 2, ...) for both backends
            self._item_id_to_idx = {item_id: idx for idx, item_id in enumerate(item_ids)}
            self._idx_to_item_id = {idx: item_id for idx, item_id in enumerate(item_ids)}
            self._item_embeddings_matrix = np.array(embeddings)
            
            # Build backend-specific index
            if self.backend == 'annoy':
                self._build_annoy_index(item_ids, embeddings)
            else:
                self._build_sklearn_index(item_ids, embeddings)
        else:
            self._item_embeddings = {}
            self._item_embeddings_matrix = None
            self._nn_index = None
            self._annoy_index = None
            logger.warning("No item embeddings found")
        
        # Set fitted attributes
        self.n_features_in_ = num_items
        self.n_users_ = num_users
        self.n_items_ = num_items
        
        self._log(f"Built {self.backend} index with {len(item_ids)} items")
    
    def _load_precalculated_embeddings(self, num_items: int):
        """Load pre-calculated embeddings for items in the interaction matrix.
        
        Args:
            num_items: Number of items in the interaction matrix
            
        Returns:
            Tuple of (item_ids, embeddings array)
        """
        if self._precalculated_embeddings is None:
            return [], None
        
        # Build reverse mapping: internal_id -> original_article_id
        inv_mapping = {v: k for k, v in self.item_mapping.items()} if self.item_mapping else {}

        # Prepare embeddings DataFrame for vectorized lookup.
        emb_df = self._precalculated_embeddings[['article_id', self._embedding_column]].copy()
        emb_df['article_id'] = emb_df['article_id'].astype(str)
        emb_df = emb_df.drop_duplicates(subset=['article_id'], keep='first')

        # Build lookup frame for all internal IDs at once.
        lookup = pd.DataFrame({'internal_id': np.arange(num_items, dtype=np.int64)})
        lookup['article_id'] = lookup['internal_id'].map(inv_mapping)
        lookup = lookup.dropna(subset=['article_id'])
        if lookup.empty:
            self._log("Loaded 0 pre-calculated embeddings")
            return [], None

        lookup['article_id'] = lookup['article_id'].astype(str)
        merged = lookup.merge(emb_df, on='article_id', how='left')

        valid_mask = merged[self._embedding_column].map(
            lambda emb: emb is not None and hasattr(emb, '__len__') and len(emb) > 0
        )
        merged = merged.loc[valid_mask]

        if merged.empty:
            self._log("Loaded 0 pre-calculated embeddings")
            return [], None

        item_ids = merged['internal_id'].astype(int).tolist()
        embeddings = np.vstack(
            merged[self._embedding_column].map(lambda emb: np.asarray(emb, dtype=np.float32)).values
        )

        self._log(f"Loaded {len(item_ids)} pre-calculated embeddings")
        if len(item_ids) > 0:
            return item_ids, embeddings
        return [], None
    
    def _encode_content(self, num_items: int):
        """Encode content using SentenceTransformer model.
        
        Args:
            num_items: Number of items in the interaction matrix
            
        Returns:
            Tuple of (item_ids, embeddings array)
        """
        # Collect items with content
        item_ids = []
        content_texts = []
        
        for item_id in range(num_items):
            text = self.content.get(item_id)
            if text:
                item_ids.append(item_id)
                content_texts.append(text)
        
        if not content_texts:
            logger.warning("No item content found to encode")
            return [], None
        
        # Encode item content with GPU batching for efficiency
        batch_size = 128 if self.model.device.type == 'cuda' else 32
        embeddings = self.model.encode(
            content_texts,
            show_progress_bar=self.verbose,
            batch_size=batch_size,
            convert_to_numpy=True,
        )
        
        return item_ids, embeddings
    
    def _build_sklearn_index(self, item_ids, embeddings):
        """Build sklearn NearestNeighbors index."""
        n_neighbors = min(self.num_neighbors, len(item_ids))
        self._nn_index = NearestNeighbors(n_neighbors=n_neighbors, metric=self.metric)
        self._nn_index.fit(self._item_embeddings_matrix)
    
    def _build_annoy_index(self, item_ids, embeddings):
        """Build Annoy index with proper sequential indexing.
        
        IMPORTANT: Annoy indices must be sequential (0, 1, 2, ...).
        Using sparse IDs (like article_id=3198681) causes Annoy to create
        a huge sparse internal array, leading to poor search results.
        
        NOTE: Annoy has a known bug on Apple Silicon (M1/M2/M3 Macs) where
        it only returns 1 neighbor regardless of how many are requested.
        Use backend='sklearn' on Apple Silicon systems.
        """
        # Convert metric for Annoy
        annoy_metric = 'angular' if self.metric == 'cosine' else self.metric
        
        self._annoy_index = AnnoyIndex(self._embedding_dim, annoy_metric)
        
        # CRITICAL: Use sequential indices (0, 1, 2, ...), NOT item_ids!
        for idx, embedding in enumerate(embeddings):
            self._annoy_index.add_item(idx, embedding)
        
        self._annoy_index.build(self.annoy_n_trees)
        
        # Verify the index
        n_items = self._annoy_index.get_n_items()
        self._log(f"Annoy index built: {n_items} items, {self.annoy_n_trees} trees, metric={annoy_metric}")
        if n_items != len(item_ids):
            logger.warning(f"Annoy index size mismatch! Got {n_items}, expected {len(item_ids)}")
    
    def _predict(self, X: csr_matrix) -> csr_matrix:
        """Generate predictions for users.
        
        Optimized with batched user embedding computation and batched NN queries.
        
        Args:
            X: User-item interaction matrix
            
        Returns:
            Prediction matrix
        """
        num_users, num_items = X.shape
        result = lil_matrix((num_users, num_items), dtype=np.float32)
        
        # Check if we have an index
        has_index = (self.backend == 'sklearn' and self._nn_index is not None) or \
                    (self.backend == 'annoy' and self._annoy_index is not None)
        
        if not has_index or self._item_embeddings_matrix is None:
            logger.warning("No item embeddings available for prediction")
            return result.tocsr()
        
        # Build item_id to embedding index mapping for vectorized lookup
        embedding_matrix = self._item_embeddings_matrix
        item_id_to_emb_idx = self._item_id_to_idx
        
        # Compute user embeddings in batches
        user_embeddings_list = []
        valid_user_ids = []
        user_item_sets = []
        
        for user_id in range(num_users):
            user_items = X[user_id].nonzero()[1]
            
            if len(user_items) == 0:
                continue
            
            # Get embeddings for items user interacted with
            emb_indices = [item_id_to_emb_idx.get(item_id) for item_id in user_items]
            emb_indices = [idx for idx in emb_indices if idx is not None]
            
            if not emb_indices:
                continue
            
            # Compute user embedding as mean of item embeddings (vectorized)
            user_embedding = embedding_matrix[emb_indices].mean(axis=0)
            
            user_embeddings_list.append(user_embedding)
            valid_user_ids.append(user_id)
            user_item_sets.append(set(user_items))
        
        if not user_embeddings_list:
            self._log("No valid user embeddings to generate recommendations")
            return result.tocsr()
        
        user_embeddings = np.array(user_embeddings_list)
        
        # Batch query for sklearn backend
        if self.backend == 'sklearn':
            distances, nn_indices = self._nn_index.kneighbors(user_embeddings)
            
            for i, user_id in enumerate(valid_user_ids):
                user_items_set = user_item_sets[i]
                recommendations = []
                
                for matrix_idx, dist in zip(nn_indices[i], distances[i]):
                    item_id = self._idx_to_item_id[matrix_idx]
                    if item_id not in user_items_set:
                        score = self._distance_to_similarity(dist)
                        recommendations.append((item_id, score))
                
                # Take top-k
                recommendations.sort(key=lambda x: x[1], reverse=True)
                
                for item_id, score in recommendations[:self.num_neighbors]:
                    if 0 <= item_id < num_items:
                        result[user_id, item_id] = score
        else:
            # Annoy doesn't support batch queries, fall back to sequential
            for i, user_id in enumerate(valid_user_ids):
                user_embedding = user_embeddings[i]
                user_items_set = user_item_sets[i]
                
                nn_indices, distances = self._query_annoy(user_embedding)
                recommendations = []
                
                for matrix_idx, dist in zip(nn_indices, distances):
                    item_id = self._idx_to_item_id[matrix_idx]
                    if item_id not in user_items_set:
                        score = self._distance_to_similarity(dist)
                        recommendations.append((item_id, score))
                
                recommendations.sort(key=lambda x: x[1], reverse=True)
                
                for item_id, score in recommendations[:self.num_neighbors]:
                    if 0 <= item_id < num_items:
                        result[user_id, item_id] = score
        
        self._log(f"Generated recommendations for {len(valid_user_ids)}/{num_users} users")
        
        return result.tocsr()
    
    def _query_sklearn(self, user_embedding: np.ndarray):
        """Query sklearn NearestNeighbors index."""
        user_embedding = user_embedding.reshape(1, -1)
        distances, nn_indices = self._nn_index.kneighbors(user_embedding)
        return nn_indices[0], distances[0]
    
    def _query_annoy(self, user_embedding: np.ndarray):
        """Query Annoy index with proper search_k.
        
        NOTE: Annoy has a known bug on Apple Silicon (M1/M2/M3 Macs) where
        it only returns 1 neighbor regardless of how many are requested.
        Use backend='sklearn' on Apple Silicon systems.
        """
        # Calculate search_k if auto
        search_k = self.annoy_search_k
        if search_k < 0:
            search_k = self.annoy_n_trees * self.num_neighbors * 10  # Be generous
        
        # Check index state
        n_items_in_index = self._annoy_index.get_n_items()
        if n_items_in_index == 0:
            logger.warning("Annoy index is empty!")
            return [], []
        
        # Query returns sequential indices, not item IDs!
        nn_indices, distances = self._annoy_index.get_nns_by_vector(
            user_embedding,
            min(self.num_neighbors, n_items_in_index),
            search_k=search_k,
            include_distances=True,
        )
        
        return nn_indices, distances
    
    def _distance_to_similarity(self, distance: float) -> float:
        """Convert distance to similarity score.
        
        Args:
            distance: Distance value from sklearn or Annoy
            
        Returns:
            Similarity score
        """
        if self.backend == 'annoy':
            # Annoy angular distance: sqrt(2 * (1 - cos(u, v)))
            # So: cos(u, v) = 1 - (distance^2 / 2)
            return max(0, 1.0 - (distance ** 2) / 2.0)
        elif self.metric == 'cosine':
            # sklearn cosine distance: 1 - cos_sim
            # So similarity = 1 - dist
            return 1.0 - distance
        elif self.metric == 'euclidean':
            return np.exp(-distance)
        else:
            return 1.0 / (1.0 + distance)
